// EN: Runs the Service 1 security suite (test/security.test.js) and writes the evidence table
//     docs/evidence/s1/security_results.md FROM THAT RUN: ID | scenario | expected | actual | pass/fail.
//     Nothing in the table is typed by hand. Run from services/employee-training:  npm run test:security
//     It needs the same database settings as npm test (S1_TEST_DB_HOST ... see test-support/helpers.js).
// Franco: Beyshaghal security tests bta3et Service 1 w yekteb gadwal el evidence MEN EL TASHGHEEL DA:
//     ID | scenario | expected | actual | pass/fail. Mafeesh 7aga fel gadwal maktooba b-eedena.
'use strict';
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { spawnSync } = require('node:child_process');

const serviceDir = path.resolve(__dirname, '..');
const outFile = path.resolve(serviceDir, '..', '..', 'docs', 'evidence', 's1', 'security_results.md');
const tmp = path.join(fs.mkdtempSync(path.join(os.tmpdir(), 's1-sec-')), 'results.json');

if (!process.env.S1_TEST_DB_HOST) {
  console.error('Set S1_TEST_DB_HOST (and the other S1_TEST_* values) first. See test-support/helpers.js.');
  process.exit(1);
}

// EN: run only the security file, exactly like npm test would, and keep its real output.
// Franco: neshaghal file el security bas, zay npm test bel zabt, w ne7tefez bel output el 7a2i2i.
const run = spawnSync(process.execPath, ['--test', 'test/security.test.js'], {
  cwd: serviceDir, env: { ...process.env, S1_SECURITY_RESULTS: tmp }, encoding: 'utf8',
});
process.stdout.write(run.stdout);
process.stderr.write(run.stderr);
if (!fs.existsSync(tmp)) {
  console.error('The security tests did not produce results (database not reachable?). No report written.');
  process.exit(1);
}

const results = JSON.parse(fs.readFileSync(tmp, 'utf8'));
const cell = (v) => String(v).replace(/\|/g, '\\|');
const passed = results.filter((r) => r.pass).length;
const lines = [
  '# Service 1 security test results',
  '',
  `Generated by \`npm run test:security\` (services/employee-training/scripts/security-report.js) on ${new Date().toISOString()}.`,
  'Every "Actual" value below was recorded by the test from the real response; nothing is typed by hand.',
  'Run against: the real Service 1 app, PostgreSQL with infra/db/seed.sql (app connected as svc_s1), and the real',
  'token checks in services/common/auth.js. Re-run the command to refresh this file.',
  '',
  `**Result: ${passed} / ${results.length} passed.**`,
  '',
  '| ID | Scenario | Expected | Actual | Result |',
  '|---|---|---|---|---|',
  ...results.map((r) => `| ${r.id} | ${cell(r.scenario)} | ${cell(r.expected)} | ${cell(r.actual)} | ${r.pass ? 'PASS' : 'FAIL'} |`),
  '',
  'Covers: unauthenticated access (01), invalid/forged/tampered tokens (02-06), wrong role (07-09), ownership and',
  'IDOR (10-15), SQL injection and invalid input (16-19), database least privilege (20), security logging (21).',
  '',
];
fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, lines.join('\n'));
fs.rmSync(path.dirname(tmp), { recursive: true, force: true });
console.log(`\nWrote ${path.relative(process.cwd(), outFile)} (${passed}/${results.length} passed).`);
process.exit(run.status === 0 ? 0 : 1);
